# Import required libraries
import random
import math
import datetime

# ---------------- Random Library ----------------
# This library is used to generate random numbers.
random_number = random.randint(1, 100)
print("Random Number:", random_number)

# ---------------- Math Library ----------------
# This library is used to perform mathematical operations.
number = 25
print("Square Root of", number, "=", math.sqrt(number))
print("Power (5^3) =", math.pow(5, 3))

# ---------------- Datetime Library ----------------
# This library is used to display the current date and time.
current = datetime.datetime.now()
print("Current Date and Time:", current)